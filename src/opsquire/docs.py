"""Generated docs: a catalog of everything in the home and an API page per general script, built from code
(module/function docstrings and signatures), tests (what the code guarantees), meta.json and run records.
Agents read these before opening code; nothing here is edited by hand."""

from __future__ import annotations

import ast
import datetime as dt
import re
from pathlib import Path
from typing import Any

from .model import (
    Task,
    all_task_folders,
    code_version,
    home_dir,
    iso,
    load_task,
    now,
    offboarded_folders,
    validate_outcome,
    write_text,
)
from .query import runs_for, task_status, used_by

CATALOG_DAYS = 14
BRIEF_CHARS = 120
AUTO_CLOSED_BY = "opsquire run (auto)"
SETTLED = frozenset({"done", "partial", "superseded", "abandoned", "archived"})
HEADER = "<!-- generated by `opsquire docs`; do not edit, regenerate instead -->\n"


def docs_dir() -> Path:
    return home_dir() / "docs"


def first_line(doc: str | None) -> str:
    return (doc or "").strip().split("\n\n")[0].replace("\n", " ").strip()


def signature(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    return f"{fn.name}({ast.unparse(fn.args)}){ret}"


def module_api(path: Path) -> dict[str, Any]:
    try:
        tree = ast.parse(path.read_text())
    except (OSError, SyntaxError) as e:
        return {"doc": f"(unparseable: {type(e).__name__})", "functions": [], "classes": []}
    functions = [
        (signature(n), first_line(ast.get_docstring(n)))
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_")
    ]
    classes = []
    for n in tree.body:
        if isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
            methods = [
                (signature(m), first_line(ast.get_docstring(m)))
                for m in n.body
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)) and not m.name.startswith("_")
            ]
            classes.append((n.name, first_line(ast.get_docstring(n)), methods))
    return {"doc": (ast.get_docstring(tree) or "").strip(), "functions": functions, "classes": classes}


def guarantees(path: Path) -> list[str]:
    """Test names as plain sentences: what the tests check."""
    try:
        tree = ast.parse(path.read_text())
    except (OSError, SyntaxError):
        return []
    out = []
    for cls in tree.body:
        if isinstance(cls, ast.ClassDef):
            for m in cls.body:
                if isinstance(m, ast.FunctionDef) and m.name.startswith("test_"):
                    out.append(f"{cls.name}: {m.name[5:].replace('_', ' ')}")
    return out


def final_mode(task: Task) -> str:
    """The mode whose `ok` run means the task did its job: apply for a changing task, read otherwise."""
    return "apply" if task.meta and task.meta.changes_prod else "read"


def run_stats(runs: list[dict[str, Any]], final: dict[str, str]) -> dict[str, Any]:
    """Runs, successes (ok in the owning task's final mode), runs per success (how much operator time each success
    cost; well above 2, one dry and one apply, says the script was debugged by rerunning it) and script versions:
    an all-ok read task run five times with five versions was debugged the same way."""
    ok = sum(1 for r in runs if r.get("status") == "ok" and r.get("mode") == final.get(str(r.get("task_id"))))
    per_ok = f"{len(runs) / ok:.1f}" if ok else "never"
    versions = {(r.get("task_id"), code_version(r.get("files") or {})) for r in runs}
    return {"runs": len(runs), "ok": ok, "per_ok": per_ok, "versions": len(versions)}


def stats_text(s: dict[str, Any], mode: str, versions: bool = False) -> str:
    if not s["runs"]:
        return "never run"
    text = f"runs {s['runs']}, {s['ok']} ok {mode}"
    if mode == "apply" and s["ok"]:
        text += f", {s['per_ok']} runs per ok apply"
    if versions and s["versions"] > 1:
        text += f", {s['versions']} script versions"
    return text


def usage(task: Task, tasks: list[Task], gone: list[Task]) -> dict[str, Any]:
    """Who uses a general script and how its runs went; offboarded users still count in the run history."""
    users = used_by(task.id, tasks)
    past = used_by(task.id, gone)
    final = {t.id: final_mode(t) for t in [*tasks, *gone]}
    runs = [r for tid in [task.id, *users, *past] for r in runs_for(tid)]
    last = max((str(r.get("started")) for r in runs), default="")
    return {"users": users, "past": past, "last_run": last, **run_stats(runs, final)}


def users_text(u: dict[str, Any]) -> str:
    return f"used by {len(u['users'])}" + (f", {len(u['past'])} offboarded" if u["past"] else "")


def api_page(task: Task, u: dict[str, Any]) -> str:
    meta = task.raw
    lines = [HEADER, f"# {task.id}\n", f"{meta.get('purpose', '')}\n"]
    targets = ", ".join(meta.get("targets") or [])
    lines.append(f"- kind: {task.kind}; changes prod: {meta.get('changes_prod')}; targets: {targets}")
    lines.append(f"- lint: {task_status(task, [])}")
    lines.append(f"- used by: {', '.join(u['users']) or ('nothing active' if u['past'] else 'nothing yet')}")
    if u["past"]:
        lines.append(f"- used by offboarded tasks: {', '.join(u['past'])}")
    lines.append(f"- runs (it and its users): {stats_text(u, final_mode(task))}, last {u['last_run'] or 'never'}\n")
    code = sorted(p for p in task.folder.glob("*.py") if not p.name.startswith("test_"))
    for path in code:
        api = module_api(path)
        lines.append(f"## {path.name}\n")
        if api["doc"]:
            lines.append(api["doc"] + "\n")
        for sig, doc in api["functions"]:
            lines.append(f"- `{sig}`" + (f": {doc}" if doc else ""))
        for name, doc, methods in api["classes"]:
            lines.append(f"- class `{name}`" + (f": {doc}" if doc else ""))
            lines += [f"  - `{sig}`" + (f": {d}" if d else "") for sig, d in methods]
        lines.append("")
    checks = [g for p in sorted(task.folder.glob("test_*.py")) for g in guarantees(p)]
    lines.append("## What the tests guarantee\n")
    lines += [f"- {g}" for g in checks] or ["- (no tests)"]
    return "\n".join(lines) + "\n"


def brief(text: object, limit: int = BRIEF_CHARS) -> str:
    """The first sentence, cut at a word boundary to `limit` characters; `opsquire show` has the rest."""
    first = re.split(r"(?<=[.!?])\s", str(text or "").strip(), maxsplit=1)[0]
    if len(first) <= limit:
        return first
    return first[:limit].rsplit(" ", 1)[0].rstrip(",;:") + " ..."


def catalog(tasks: list[Task], gone: list[Task], usages: dict[str, dict[str, Any]]) -> str:
    """Every general script in full; of the tasks, those created in the last CATALOG_DAYS days and every one not
    settled yet, each in brief. `opsquire find` covers the rest, so the catalog stays short enough for an agent to
    read."""
    rows = [HEADER, "# Opsquire catalog\n", "Read this before opening code. Reuse before writing anything new.\n"]
    general = [t for t in tasks if t.kind == "general"]
    rows.append("## General scripts (reusable)\n")
    for t in general:
        u = usages[t.id]
        tests = sum(len(guarantees(p)) for p in t.folder.glob("test_*.py"))
        rows.append(
            f"- **{t.id}**: {t.raw.get('purpose', '')} "
            f"({task_status(t, [])}; tests: {tests}; {users_text(u)}; {stats_text(u, final_mode(t))}) "
            f"-> docs/{t.id}.md"
        )
    if not general:
        rows.append("- (none yet)")
    final = {t.id: final_mode(t) for t in tasks}
    since = iso(now() - dt.timedelta(days=CATALOG_DAYS))
    left = 0
    shown_rows: list[str] = []
    for t in tasks:
        if t.kind == "general":
            continue
        runs = runs_for(t.id)
        status = task_status(t, runs)
        if status in SETTLED and str(t.raw.get("created") or "") < since:
            left += 1
            continue
        uses = t.raw.get("uses") or []
        extra = f" (uses {', '.join(uses)})" if uses else ""
        stats = stats_text(run_stats(runs, final), final_mode(t), versions=True)
        closed = t.raw.get("outcome") if not validate_outcome(t.raw.get("outcome")) else None
        closing = ""
        if closed and closed["closed_by"] != AUTO_CLOSED_BY:
            closing = f" Closed {closed['state']} by {closed['closed_by']}: {brief(closed['note'], BRIEF_CHARS // 2)}"
        shown_rows.append(f"- {t.id} [{status}, {t.kind}; {stats}]: {brief(t.raw.get('purpose'))}{extra}{closing}")
    rows.append(f"\n## Tasks and plans: the last {CATALOG_DAYS} days and everything still open\n")
    rows.append(
        "Runs are operator time. Above 2 runs per ok apply (one dry, one apply), or a read task run many times, "
        "means the task was debugged by rerunning it; several script versions say the script changed between runs.\n"
    )
    rows += shown_rows
    if left:
        rows.append(
            f"\n{left} older settled tasks are left out: `opsquire find <words>` searches every task, its design, "
            "runs and thread."
        )
    if gone:
        scripts = sum(1 for t in gone if t.kind == "general")
        rows.append(
            f"\n## Offboarded\n\n{len(gone) - scripts} settled tasks idle past the retention"
            + (f" and {scripts} general scripts taken out by hand" if scripts else "")
            + " are in offboarded/ and left out above. `opsquire find` still finds them, `opsquire show <id>` reads "
            "one, `opsquire restore <id>` brings it back."
        )
    return "\n".join(rows) + "\n"


def write_docs() -> Path:
    tasks = [load_task(f) for f in all_task_folders()]
    gone = [load_task(f) for f in offboarded_folders()]
    out = docs_dir()
    out.mkdir(exist_ok=True)
    wanted = {"CATALOG.md"}
    usages = {t.id: usage(t, tasks, gone) for t in tasks if t.kind == "general"}
    write_text(out / "CATALOG.md", catalog(tasks, gone, usages))
    for t in tasks:
        if t.kind == "general":
            wanted.add(f"{t.id}.md")
            write_text(out / f"{t.id}.md", api_page(t, usages[t.id]))
    for stale in out.glob("*.md"):
        if stale.name not in wanted and re.match(r"^[a-z0-9_.-]+\.md$", stale.name):
            stale.unlink()
    return out
